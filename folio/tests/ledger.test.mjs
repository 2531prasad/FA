test('line diffs retain content and accurate line numbers', () => {
  const diff = lineDiff('alpha\nbeta\ngamma\n','alpha\nnew\nbeta\ndelta\n');
  assert.equal(diff.filter(l=>l.type!=='added').map(l=>l.text).join('\n'),'alpha\nbeta\ngamma\n');
  assert.equal(diff.filter(l=>l.type!=='removed').map(l=>l.text).join('\n'),'alpha\nnew\nbeta\ndelta\n');
  assert.deepEqual(diff.find(l=>l.text==='new'),{type:'added',text:'new',oldLine:null,newLine:2});
  assert.deepEqual(diff.find(l=>l.text==='gamma'),{type:'removed',text:'gamma',oldLine:3,newLine:null});
  assert.equal(lineDiff('same','same').filter(l=>l.type!=='context').length,0);
});

test('local ledger discovers files, persists revisions and protects edits', async t => {
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'folio-test-'));
  let server;
  t.after(async()=>{if(server?.listening)await new Promise(resolve=>server.close(resolve));await fs.rm(root,{recursive:true,force:true});});
  await fs.mkdir(path.join(root,'Reports'));
  const content='# My research\n\nPrepared 12 October 2026.\n\n**A section**\n\nA careful first thought.\n';
  const file=path.join(root,'Reports','initial.md');
  await fs.writeFile(file,content);
  await fs.writeFile(path.join(root,'README.md'),'# Not a report');
  await fs.writeFile(path.join(root,'ledger.config.json'),JSON.stringify({reports:{'Reports/initial.md':{label:'Review',kind:'Review',query:'Test research query'}}}));
  let ledger=await createLedger({root,pollMs:60_000});server=ledger.server;
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  let base=`http://127.0.0.1:${server.address().port}`;
  let index=await (await fetch(base+'/api/reports')).json();
  assert.equal(index.reports.length,1);assert.equal(index.reports[0].label,'Review');assert.deepEqual(index.reports[0].headings,['A section']);
  assert.equal(index.reports[0].revisions,1);assert.equal(index.reports[0].prepared,'12 October 2026');
  assert.equal(index.reports[0].query,'Test research query');
  assert.equal(index.reports[0].role,null);assert.equal(index.reports[0].canonical,false);
  const font=await fetch(base+'/fonts/ArchivoBlack-Regular.ttf');
  assert.equal(font.status,200);assert.match(font.headers.get('content-type'),/^font\/ttf/);
  const researchAsset=await fetch(base+'/research.js');
  assert.equal(researchAsset.status,200);assert.match(researchAsset.headers.get('content-type'),/^text\/javascript/);
  assert.match(await researchAsset.text(),/FAResearch/);
  const minimapAsset=await fetch(base+'/minimap.js');
  assert.equal(minimapAsset.status,200);assert.match(await minimapAsset.text(),/FAMinimap/);
  const report=await (await fetch(base+'/api/report?path=Reports%2Finitial.md')).json();
  const initialHash=report.hash;
  assert.equal(report.content,content);
  assert.equal((await fetch(base+'/.ledger/anything')).status,404);
  assert.equal((await fetch(base+'/api/report?path=../outside.md')).status,404);
  assert.equal((await fetch(base+'/api/reports',{headers:{Origin:'https://evil.example'}})).status,403);
  const save=input=>fetch(base+'/api/report',{method:'PUT',headers:{'Content-Type':'application/json','X-Ledger-Token':index.token},body:JSON.stringify(input)});
  assert.equal((await fetch(base+'/api/report',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({path:'Reports/initial.md',content:'bad'})})).status,403);
  const external=content+'\nExternal observation.\n';await fs.writeFile(file,external);await ledger.scan();
  assert.equal((await save({path:'Reports/initial.md',hash:initialHash,content:'stale'})).status,409);
  assert.equal(await fs.readFile(file,'utf8'),external);
  let latest=await (await fetch(base+'/api/report?path=Reports%2Finitial.md')).json();
  const edited=external.replace('careful first','revised second');
  assert.equal((await save({path:latest.path,hash:latest.hash,content:edited,note:'Reconsidered the first thought'})).status,200);
  assert.equal(await fs.readFile(file,'utf8'),edited);
  let history=await (await fetch(base+'/api/history?path=Reports%2Finitial.md')).json();
  assert.equal(history.history.length,3);assert.equal(history.history[0].source,'Browser edit');assert.equal(history.history[0].note,'Reconsidered the first thought');
  assert.equal(history.history[0].added,1);assert.equal(history.history[0].removed,1);
  const revision=await (await fetch(base+'/api/history?path=Reports%2Finitial.md&revision='+history.history[0].id)).json();
  assert.equal(revision.content,edited);assert.ok(revision.diff.some(l=>l.type==='added'&&l.text.includes('revised second')));
  await ledger.scan();assert.equal((await (await fetch(base+'/api/history?path=Reports%2Finitial.md')).json()).history.length,3);
  await new Promise(resolve=>server.close(resolve));
  ledger=await createLedger({root,pollMs:60_000});server=ledger.server;
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));base=`http://127.0.0.1:${server.address().port}`;
  index=await (await fetch(base+'/api/reports')).json();assert.equal(index.reports[0].revisions,3);
  await fs.writeFile(path.join(root,'new.md'),'# A new report\n\n[Source](Reports/initial.md)');await ledger.scan();
  index=await (await fetch(base+'/api/reports')).json();assert.equal(index.reports.length,2);assert.deepEqual(index.reports.find(r=>r.path==='new.md').links,['Reports/initial.md']);
  await fs.symlink('/etc/hosts',path.join(root,'escape.md'));await ledger.scan();
  assert.equal((await (await fetch(base+'/api/reports')).json()).reports.length,2);
  await fs.unlink(file);await ledger.scan();
  assert.equal((await fetch(base+'/api/report?path=Reports%2Finitial.md')).status,404);
  const importReport=input=>fetch(base+'/api/import',{method:'POST',headers:{'Content-Type':'application/json','X-Ledger-Token':index.token},body:JSON.stringify(input)});
  assert.equal((await fetch(base+'/api/import',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({filename:'unauthorized.md',content:'# Bad'})})).status,403);
  for(const filename of ['../escape.md','/outside.md','.hidden.md','README.md','AGENTS.md','readme.md','agents.md','report.html'])assert.equal((await importReport({filename,content:'# Bad'})).status,400,filename);
  assert.equal((await importReport({filename:'blank.md',content:'  '})).status,400);
  assert.equal((await importReport({filename:'large.md',content:'a'.repeat(2*1024*1024+1)})).status,400);
  await fs.symlink(path.join(root,'Reports'),path.join(root,'Imported'));
  assert.equal((await importReport({filename:'symlink.md',content:'# Bad'})).status,403);
  await assert.rejects(fs.access(path.join(root,'Reports','symlink.md')));
  await fs.unlink(path.join(root,'Imported'));
  const imported='# Independent perspective\n\n**Report role:** Independent FA\n**Model / agent:** Model A\n**Research query:** Shared scope\n**Research brief:** brief-01\n**Information cutoff:** 2026-10-13\n\n## Analysis\n\nOriginal Markdown, retained exactly.\n';
  assert.equal((await importReport({filename:'new-perspective.md',content:imported})).status,201);
  assert.equal(await fs.readFile(path.join(root,'Imported','new-perspective.md'),'utf8'),imported);
  assert.equal((await importReport({filename:'new-perspective.md',content:'# Overwrite'})).status,409);
  assert.equal(await fs.readFile(path.join(root,'Imported','new-perspective.md'),'utf8'),imported);
  const importedHistory=await (await fetch(base+'/api/history?path=Imported%2Fnew-perspective.md')).json();
  assert.equal(importedHistory.history.length,1);
  const importedReport=await (await fetch(base+'/api/report?path=Imported%2Fnew-perspective.md')).json();
  assert.equal(importedReport.content,imported);assert.equal(importedReport.role,'independent');assert.equal(importedReport.model,'Model A');assert.equal(importedReport.query,'Shared scope');
  const other=await (await fetch(base+'/api/report?path=new.md')).json();
  const synthesis=`# Canonical synthesis\n\n**Report role:** Synthesis\n**Status:** Canonical\n**Research query:** Shared scope\n\n## Source reports\n\n**Source report:** [Independent](new-perspective.md) | SHA-256: ${importedReport.hash}\n\n**Source report:** [Other](../new.md) | SHA-256: ${other.hash}\n`;
  assert.equal((await importReport({filename:'canonical.md',content:synthesis})).status,201);
  const canonical=await (await fetch(base+'/api/report?path=Imported%2Fcanonical.md')).json();
  assert.equal(canonical.canonical,true);assert.equal(canonical.role,'synthesis');assert.deepEqual(canonical.sourceReports,[{path:'Imported/new-perspective.md',hash:importedReport.hash},{path:'new.md',hash:other.hash}]);
  await fs.writeFile(path.join(root,'Imported','new-perspective.md'),imported+'\nLater evidence.\n');await ledger.scan();
  const sourceHistory=await (await fetch(base+'/api/history?path=Imported%2Fnew-perspective.md')).json();
  const pinned=sourceHistory.history.find(revision=>revision.hash===importedReport.hash);assert.ok(pinned);
  assert.equal((await (await fetch(base+'/api/history?path=Imported%2Fnew-perspective.md&revision='+pinned.id)).json()).content,imported);
  assert.equal((await (await fetch(base+'/api/report?path=Imported%2Fcanonical.md')).json()).sourceReports[0].hash,importedReport.hash);
});
